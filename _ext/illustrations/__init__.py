    def apply_css_classes(self, classlist=None):
        """Assign the provided CSS classes to the <use> elements in the illustration.
 
        This method updates the SVG data in self.data, by assigning a CSS class from
        `classlist`, in the order found, to the <use> elements in the SVG.
 
        As of now, all SVG images generated by hb-view and svg_stack are structured so
        that the top-level shapes are rendered into the viewport through a <use> element.
        Consequently, CSS and JavaScript can only affect the appearance of the shapes
        through these <use>s.
        """
        # Change of thought; we don't start out with any classes at all, so we don't need to check
        # for the presence of all of the possibilities. Perhaps we'll need to for some future SVG
        # component generator, but for now we can just add the ones requested in self.cssclasses.
         
        print(f'[{self.name}]: Applying CSS classes to the <use> elements in the illustration.', file=sys.stderr)
 
        if not classlist:
            classlist = self.cssclasses
             
        if not self.data:
            raise ValueError(f'[{self.name}]: The illustration does not contain SVGs in its .data attribute;'
                             'it must be built before CSS classes can be assigned.')
        else:
            # Check the length of the classlist
            u_count = self.data.count("<use ")
            c_count = len(classlist)
            if u_count != c_count:
                raise ValueError(f'[{self.name}]: Mismatched CSS-class count. Found {u_count} <use> elements but {c_count} CSS classes were provided.')
            else:
                # Ugly, but works for the moment. All SVGs from hb-view and svg_stack use this namespace string....
                namespace = "{http://www.w3.org/2000/svg}"
                #tree = ET.parse(self.data)
                tree = ET.ElementTree(ET.fromstring(self.data))
                root = tree.getroot()
 
                # This nsmap stuff can probably be removed; we could then remove lxml
                # from the build requirements....
                d = root.nsmap
                #print(d)
                #del d[None]
                #d["svg"] = namespace[1:-1]
                #print(d)
                #print(root.tag)
 
                # Check whether or not this is an SVG tree that we know how to work with
                if (root.tag != namespace + "svg"):
                    print(f'[{self.name}]: Parsing trouble; it\'s unclear if this is a compatible SVG', file=sys.stderr)
                    raise ValueError(f'Root element: {root.tag}')
                else:
                    # iterate through the entire tree
                    elems = list(root.iter())
                    for elem in elems:
                        # inserting a generic 'class=""' into each <use> element
                        if (elem.tag == namespace + "use"):
                            if ("class" not in elem.attrib):
                                # TODO: support a user-supplied class attribute, either directly
                                #       or via a class list for the whole file, which we
                                #       would then store in the docs.
                                # TODO: append to the class, rather than replacing it.
                                #       Not sure how duplicate classes would be handled by ETree....
                                elem.attrib["class"] = classlist.pop(0)
                                print(elem.tag, elem.attrib["class"])
                            else:
                                # We should pass pre-existing class attributes through, not considering them errors
                                print(f'[{self.name}]: Unexpected: encountered a <use> element with non-empty classes', file=sys.stderr)
                                raise NotImplementedError(f'{elem.tag} has CSS classes: {elem.attrib["class"]}')
 
                    # Paste the updated tree back to self.data ... as a string, since it was before ??
                    self.data = ET.tostring(tree, encoding="unicode")
                 
        return None
 
     
    def prepend_elementIDs(self, svg_data, id_prefix):
        """Insert a prefix into the ID of  each SVG element, to ensure uniqueness.
 
        This function is meant to guarantee that every SVG and all of that SVGs child
        elements has an ID attribute that is unique within the entire document. The
        uniqueness is mandatory because the SVG images are inlined into the HTML file
        output: any elements that share a non-unique ID would all be affected by CSS
        and JavaScript simultaneously, because all inline SVG elements belong to the
        single, shared namespace/DOM of the HTML page.
 
        The inlining itself is mandatory because CSS and JavaScript cannot modify SVG
        objects that are included on the HTML page as external <img src="foo"> elements.
        Or, at least, not reliably, and not with most browsers.
        """
        print(f'[{self.name}]: Inserting "{id_prefix}" prefixes to the ID attributes of all elements in the illustration.', file=sys.stderr)
 
        if not svg_data:
            raise ValueError(f'[{self.name}]: The illustration does not contain SVGs in its .data attribute;'
                             'it must be built before CSS classes can be assigned.')
        if not id_prefix:
            raise ValueError('No ID prefix was supplied.')
         
        # Ugly, but works for the moment. All SVGs from hb-view and svg_stack use this namespace string....
        namespace = "{http://www.w3.org/2000/svg}"
        # Load the SVG string from a variable, not a file. In lxml.ETree, that means
        # you also have to wrap the result in a new ElementTree, because for some reason
        # loading from a string returns a root, but loading the same thing from file
        # returns a tree....
        tree = ET.ElementTree(ET.fromstring(svg_data))
        root = tree.getroot()
 
        # This nsmap stuff can probably be removed; we could then remove lxml
        # from the build requirements....
        d = root.nsmap
        #print(d)
        #del d[None]
        #d["svg"] = namespace[1:-1]
        #print(d)
        #print(root.tag)
 
        # Check whether or not this is an SVG tree that we know how to work with
        if (root.tag != namespace + "svg"):
            print(f'[{self.name}]: Parsing trouble; it\'s unclear if this is a compatible SVG', file=sys.stderr)
            raise ValueError(f'Root element: {root.tag}')
        else:
            if ("id" not in root.attrib):
                # insert id_prefix as the id for the complete SVG
                #print(f'[{self.name}]: no pre-existing #id', file=sys.stderr)
                root.attrib["id"] = id_prefix
            else:
                # Need to make these actual exceptions
                print(f'[{self.name}]: Unexpected: this SVG root element already has an id!', file=sys.stderr)
                raise ValueError(f'Root id is: {root.attrib["id"]}')
                 
            # iterate through the entire tree
            elems = list(root.iter())
            for elem in elems:
                # ... prepending id_prefix to all id declarations
                if elem != root:
                    if "id" in elem.attrib:
                        print(f'[{self.name}]: {elem.tag} old id = {elem.attrib["id"]}', file=sys.stderr)
                        old_id = elem.attrib["id"]
                        if old_id[0:1] != "id":
                            elem.set("id", id_prefix + ":" + old_id)
                            print(f'[{self.name}]: Element {elem.tag}, new id: {elem.attrib["id"]}', file=sys.stderr)
                        else:
                            print(f'[{self.name}]: Error: {elem.tag} has unexpected id: {elem.attrib["id"]}', file=sys.stderr)
                            raise ValueError(f'Element id found = {elem.attrib["id"]}')
                     
                    # ... prepending id_prefix to all id hrefs
                    if ( "{" + d["xlink"] + "}" + "href" in elem.attrib):
                        print(f'[{self.name}]: Xlink element {elem.tag}, assigning id to target', file=sys.stderr)
                        old_target = elem.attrib["{" + d["xlink"] + "}" + "href"]
                        # sample::
                        #       before prepend:
                        #                      <use xlink:href="#glyph0-1" 
                        #        after prepend:
                        #                      <use xlink:href="#bengali-ccmp:id2:glyph-0-1"
                        # TODO: test whether the following syntax (which is used to access the xlink href)
                        #       also gets written out correctly to the file.
 
                        if old_target[1:2] != "id":
                            elem.set("{" + d["xlink"] + "}" + "href", "#" + id_prefix + ":" + old_target[1:])
                            print(f'[{self.name}]: {elem.attrib}', file=sys.stderr)
                        else:
                            print(f'[{self.name}]: Unexpected, element {elem.tag} has unexpected target: {old_target}', file=sys.stderr)
 
        # Return the altered SVG as a string, since it's intended to be written to file
        return ET.tostring(tree, encoding="unicode")
 
 
    def write(self, filename_stub=None):
        """Write the illustration to an SVG file, using the supplied filename stub.
 
        This will also write out any requested duplicate illustrations into their own
        SVG files, using the filename stubs found in the `duplicates` block in the
        YAML configuration file for the primary illustration."""
        print(f'[{self.name}]: Writing SVG content out to files', file=sys.stderr)
 
        if not filename_stub:
            filename_stub = self.name
         
        if not self.data:
            raise ValueError(f'[{self.name}]: Writing to file: the illustration does not contain SVGs in its .data attribute;'
                             'it must be built before it can be written out to file.')

        # Regardless of whether there are or are not any duplicates (as tested below), 
        # apply element IDs to self.data, using the unaltered name, then write that out
        # to file.
        # Here, as elsewhere, we probably don't need to update self.data. Doing so might
        # save a few cycles if we were writing again and again, but that's not the use case.
        with open(filename_stub + ".svg", 'w+t', encoding="utf-8") as outfile:
            print(f'[{self.name}]: Writing SVG content out to file {filename_stub}.svg', file=sys.stderr)
            outfile.write( self.prepend_elementIDs(self.data, filename_stub) )
 
        # Handle all requested image duplicates.
        if self.duplicates:
            # Create a copy for each entry in the self.duplicates list
            for duplicate in self.duplicates:                
                # Apply distinct element IDs to self.data, using 'duplicate' instead of
                # filename_stub.
                # Make an ET.tree for each duplicate, apply the ID, write it to
                # its own file, but don't overwrite that ET.tree back into self.data
                with open(duplicate + ".svg", 'w+t', encoding="utf-8") as outfile:
                    print(f'[{self.name}]: Writing SVG content out to duplicate illustration {duplicate}.svg', file=sys.stderr)
                    outfile.write( self.prepend_elementIDs(self.data, duplicate) )
                     
        return None
     
 
