# Margin value of hb-view is in points (1/72 in)
# https://github.com/harfbuzz/harfbuzz/issues/1186#issuecomment-424780696
#
# CSS pixels are 1/96 in
# https://developer.mozilla.org/en-US/docs/Web/CSS/Reference/Values/length#absolute_length_units
#
# :. (72 / 96)pt = 1px
# pix_margin = pt_margin * (96/72)
def hb_pt_to_px(points):
    """Convert lengths in points to the equivalent in pixels."""
    return points * (72 / 96)


def hb_px_to_pt(pixels):
    """Convert lengths in pixels to the equivalent in points."""
    return pixels * (96 / 72)


class svgComponent():
    """An individual SVG component within a full illustration.

    Here, "individual component" essentially means a image that can be
    generated by a single command. The full illustration typically consists
    of several individual components that cannot be built all at once
    because they require different feature settings, margins, or perhaps
    different source fonts.

    See also svgFileComponent, which represents the simpler case of an
    individual component that can be read from an external file and does
    not require generation.
    """
    def __init__(self,
                 name,
                 fontfile,
                 unicodes,
                 fontsize,
                 margin,
                 features=None,
                 options=None,
                 generator="hb-view",
                 basecolor="000000",
                 ):

        from pathlib import Path

        self.name = name 
        self.tree = None # May not be needed; initializing to None just so that the attribute is always there upstream
        self.root = None # Also may not be needed; root is gettable from tree

        # turn `fontfile` into an absolute path
        print(f'[Component `{self.name}`]: fontfile reference = {fontfile}', file=sys.stderr)
        p = Path(fontfile)
        if p.is_absolute():
            self.font = p
            print(f'fontfile path: {p} ... cwd: {Path.cwd()} ... absolute: {p.resolve()}')
        elif p.exists():
            if DOCROOT:
                # compose new path as DOCROOT + fontfile
                p = Path(DOCROOT, p)
                p.resolve()
                self.font = p
        else:
            raise OSError(f'[Component `{self.name}`]: the font file {fontfile} could not be located. Does {p} exist?')
        
        self.unicodes = unicodes
        self.fontsize = fontsize
        self.margin = margin
        self.features = features
        self.options = options 
        self.generator = generator
        self.basecolor = basecolor
         
        return None


    def generate(self):
        """Generate a fresh instance of the SVG component from its configuration.

         This calls out to the system to execute `self.generator`, so if the configred
         generator program is not found, the generation will fail. A simple test is
         currently used that is expected to behave reasonably on Linux and Linuxy OSes.

         At present, the only generator supported in `hb-view`. Support for any new
         generators should be added here (or, at least, started here).
         """
        #import sys # not needed; should be loaded from package
        import shutil
        import subprocess

        # test that self.generator exists
        print(f'[Component `{self.name}`]: Checking for the presence of image generator: {self.generator}', file=sys.stderr)
        if not shutil.which(self.generator):
            raise Exception(f'[Component `{self.name}`]: The image generator {self.generator} cannot be found on the system.')
        else:
            print(f'[Component `{self.name}`]: image generator {self.generator} exists', file=sys.stderr)
            # build the command
            command = [f'{self.generator}',
                       "--output-format=svg",            # generates SVG output, and sends it to stdout
                       f'--font-size={self.fontsize}',
                       f'--margin={self.margin}',
                       f'--features={self.features}',
                       f'--foreground={self.basecolor}',
                       f'--background=FFFFFF00',         # for now, make this transparent
                       f'{self.font}',                   # for hb-view, this must come next-to-last
                       f'--unicodes={self.unicodes}',    # for hb-view, this must come last
                       ]

            # call the command, capturing the results from stdout
            print(f'[Component `{self.name}`], generate command: {command}', file=sys.stderr)
            result = subprocess.run(command, capture_output=True, encoding="utf8")
            print(f'[Component `{self.name}`] generated', file=sys.stderr)
            #result = subprocess.run(command, stdout=subprocess.PIPE)
            if result.returncode:
                print(f'[Component `{self.name}`]: image generator error: return code {result.returncode}')
                raise OSError(f'[Component `{self.name}`]: {result.stderr}')

        # capture any errors and raise them as exceptions from stderr?
        return result.stdout


