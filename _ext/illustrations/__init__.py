class svgFileComponent():
    """Simple SVG component class for constituents that can be loaded directly from file.

    The original use case for this is the `right-arrow.svg` component, which is
    used in almost every illustration and (in the present understanding of things)
    needs to be identical in every case. Loading each instance from file reduces
    the need to regenerate a new, identical copy for every illustration.
    """
    def __init__(self,
                 name,
                 filepath):

        #from lxml import etree as ET # shouldn't be necessary; loads from package....
        #from pathlib import Path # shouldn't be necessary; loads from package....
        
        self.name = name

        # turn `filepath` into an absolute path
        print(f'[Component `{self.name}`]: Checking for the presence of external file: {filepath}', file=sys.stderr)
        p = Path(filepath)
        if p.exists():
            p = p.resolve()
            self.file = p
            print(f'[Component `{self.name}`]: ixternal file: {self.file} exists', file=sys.stderr)
        else:
            raise OSError(f'[Component `{self.name}`]: the font file {filepath} could not be located. Does {p} exist?')
        return None

    
    def generate(self):
        #from lxml import etree as ET # shouldn't be necessary; loads from package....
        namespace = "{http://www.w3.org/2000/svg}"

        print(f'[Component `{self.name}`], loading external file: {self.file}', file=sys.stderr)
        with open(self.file, 'r+t', encoding='utf-8') as svgfile:
            self.tree = ET.parse(svgfile)
            self.root = self.tree.getroot()

        return ET.tostring(self.tree, encoding="unicode")

    
class Illustration():
    """An SVG illustration. Each illustration is defined in a YAML file that specifies some basic properties
       and, typically, a list of components that must be individually generated as intermediate images.

       For example, there is usually a "-before" and "-after" variant of a shaping cluster, which require two
       separate commands and parameter sets to generate. The two are then typically composited into the final
       illustration with an 'arrow' image in between to separate them.

       There are some exception to this formula, however:
       - single-component illustrations, which can be generated with a single command.
       - duplicates of other illustrations, which can be generated by making a file copy of the original illustration.
       """

